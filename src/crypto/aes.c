static const uint8_t rcon[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,
};

static uint8_t xtime(uint8_t x) {
    return (x & 0x80) ? ((x << 1) ^ 0x1b) : (x << 1);
}

static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    int i;
    for (i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return p;
}

static void key_expand(const uint8_t key[16], uint8_t rk[176]) {
    int i;
    uint8_t tmp[4];

    for (i = 0; i < 16; i++) rk[i] = key[i];

    for (i = 4; i < 44; i++) {
        tmp[0] = rk[(i-1)*4+0];
        tmp[1] = rk[(i-1)*4+1];
        tmp[2] = rk[(i-1)*4+2];
        tmp[3] = rk[(i-1)*4+3];

        if (i % 4 == 0) {
            uint8_t t = tmp[0];
            tmp[0] = sbox[tmp[1]] ^ rcon[i/4];
            tmp[1] = sbox[tmp[2]];
            tmp[2] = sbox[tmp[3]];
            tmp[3] = sbox[t];
        }
        rk[i*4+0] = rk[(i-4)*4+0] ^ tmp[0];
        rk[i*4+1] = rk[(i-4)*4+1] ^ tmp[1];
        rk[i*4+2] = rk[(i-4)*4+2] ^ tmp[2];
        rk[i*4+3] = rk[(i-4)*4+3] ^ tmp[3];
    }
}

void aes128_encrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    uint8_t s[16];
    int r, i;

    key_expand(key, rk);

    for (i = 0; i < 16; i++) s[i] = in[i] ^ rk[i];

    for (r = 1; r <= 10; r++) {
        uint8_t t[16];

        for (i = 0; i < 16; i++) s[i] = sbox[s[i]];

        t[0]=s[0];  t[1]=s[5];  t[2]=s[10]; t[3]=s[15];
        t[4]=s[4];  t[5]=s[9];  t[6]=s[14]; t[7]=s[3];
        t[8]=s[8];  t[9]=s[13]; t[10]=s[2]; t[11]=s[7];
        t[12]=s[12];t[13]=s[1]; t[14]=s[6]; t[15]=s[11];

        if (r < 10) {
            for (i = 0; i < 4; i++) {
                uint8_t a0=t[i*4], a1=t[i*4+1], a2=t[i*4+2], a3=t[i*4+3];
                s[i*4+0] = gmul(a0,2)^gmul(a1,3)^a2^a3;
                s[i*4+1] = a0^gmul(a1,2)^gmul(a2,3)^a3;
                s[i*4+2] = a0^a1^gmul(a2,2)^gmul(a3,3);
                s[i*4+3] = gmul(a0,3)^a1^a2^gmul(a3,2);
            }
        } else {
            for (i = 0; i < 16; i++) s[i] = t[i];
        }

        for (i = 0; i < 16; i++) s[i] ^= rk[r*16+i];
    }

    for (i = 0; i < 16; i++) out[i] = s[i];
}

void aes128_decrypt(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    uint8_t rk[176];
    uint8_t s[16];
    int r, i;

    key_expand(key, rk);

    for (i = 0; i < 16; i++) s[i] = in[i] ^ rk[160+i];

    for (r = 9; r >= 0; r--) {
        uint8_t t[16];

        t[0]=s[0];  t[1]=s[13]; t[2]=s[10]; t[3]=s[7];
        t[4]=s[4];  t[5]=s[1];  t[6]=s[14]; t[7]=s[11];
        t[8]=s[8];  t[9]=s[5];  t[10]=s[2]; t[11]=s[15];
        t[12]=s[12];t[13]=s[9]; t[14]=s[6]; t[15]=s[3];

        for (i = 0; i < 16; i++) s[i] = inv_sbox[t[i]];

        for (i = 0; i < 16; i++) s[i] ^= rk[r*16+i];

        if (r > 0) {
            for (i = 0; i < 4; i++) {
                uint8_t a0=s[i*4], a1=s[i*4+1], a2=s[i*4+2], a3=s[i*4+3];
                t[i*4+0] = gmul(a0,0x0e)^gmul(a1,0x0b)^gmul(a2,0x0d)^gmul(a3,0x09);
                t[i*4+1] = gmul(a0,0x09)^gmul(a1,0x0e)^gmul(a2,0x0b)^gmul(a3,0x0d);
                t[i*4+2] = gmul(a0,0x0d)^gmul(a1,0x09)^gmul(a2,0x0e)^gmul(a3,0x0b);
                t[i*4+3] = gmul(a0,0x0b)^gmul(a1,0x0d)^gmul(a2,0x09)^gmul(a3,0x0e);
            }
            for (i = 0; i < 16; i++) s[i] = t[i];
        }
    }

    for (i = 0; i < 16; i++) out[i] = s[i];
}

int aes_key_unwrap(const uint8_t *kek, int kek_len,
                   const uint8_t *in,  int in_len,
                   uint8_t *out) {
    uint8_t a[8], b[16];
    int n, i, j;
    (void)kek_len;

    if (in_len < 24 || (in_len % 8) != 0) return -1;
    n = (in_len / 8) - 1;

    for (i = 0; i < 8; i++) a[i] = in[i];
    for (i = 0; i < n * 8; i++) out[i] = in[8 + i];

    for (j = 5; j >= 0; j--) {
        for (i = n; i >= 1; i--) {
            uint32_t t = (uint32_t)(n * j + i);

            a[4] ^= (uint8_t)(t >> 24);
            a[5] ^= (uint8_t)(t >> 16);
            a[6] ^= (uint8_t)(t >> 8);
            a[7] ^= (uint8_t)(t);

            for (int k = 0; k < 8; k++) b[k]   = a[k];
            for (int k = 0; k < 8; k++) b[8+k] = out[(i-1)*8+k];
            aes128_decrypt(kek, b, b);
            for (int k = 0; k < 8; k++) a[k]          = b[k];
            for (int k = 0; k < 8; k++) out[(i-1)*8+k] = b[8+k];
        }
    }

    for (i = 0; i < 8; i++) {
        if (a[i] != 0xa6) return -1;
    }
    return 0;
}
